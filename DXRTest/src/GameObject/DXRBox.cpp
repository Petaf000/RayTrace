#include "DXRBox.h"


void DXRBox::Init() {
    CreateBoxGeometry();
}

void DXRBox::UnInit() {
    m_vertices.clear();
    m_indices.clear();
}

void DXRBox::CreateBoxGeometry() {
    m_vertices.clear();
    m_indices.clear();

    float w = 0.5f;
    float h = 0.5f;
    float d = 0.5f;

    m_vertices = {
        {{-w, -h,  d}, {0, 0, 1}, {0, 1}},
        {{ w, -h,  d}, {0, 0, 1}, {1, 1}},
        {{ w,  h,  d}, {0, 0, 1}, {1, 0}},
        {{-w,  h,  d}, {0, 0, 1}, {0, 0}},

        {{ w, -h, -d}, {0, 0, -1}, {0, 1}},
        {{-w, -h, -d}, {0, 0, -1}, {1, 1}},
        {{-w,  h, -d}, {0, 0, -1}, {1, 0}},
        {{ w,  h, -d}, {0, 0, -1}, {0, 0}},

        {{ w, -h,  d}, {1, 0, 0}, {0, 1}},
        {{ w, -h, -d}, {1, 0, 0}, {1, 1}},
        {{ w,  h, -d}, {1, 0, 0}, {1, 0}},
        {{ w,  h,  d}, {1, 0, 0}, {0, 0}},

        {{-w, -h, -d}, {-1, 0, 0}, {0, 1}},
        {{-w, -h,  d}, {-1, 0, 0}, {1, 1}},
        {{-w,  h,  d}, {-1, 0, 0}, {1, 0}},
        {{-w,  h, -d}, {-1, 0, 0}, {0, 0}},

        {{-w,  h,  d}, {0, 1, 0}, {0, 1}},
        {{ w,  h,  d}, {0, 1, 0}, {1, 1}},
        {{ w,  h, -d}, {0, 1, 0}, {1, 0}},
        {{-w,  h, -d}, {0, 1, 0}, {0, 0}},

        {{-w, -h, -d}, {0, -1, 0}, {0, 1}},
        {{ w, -h, -d}, {0, -1, 0}, {1, 1}},
        {{ w, -h,  d}, {0, -1, 0}, {1, 0}},
        {{-w, -h,  d}, {0, -1, 0}, {0, 0}}
    };

    m_indices = {
        0, 1, 2,    2, 3, 0,
        4, 5, 6,    6, 7, 4,
        8, 9, 10,   10, 11, 8,
        12, 13, 14, 14, 15, 12,
        16, 17, 18, 18, 19, 16,
        20, 21, 22, 22, 23, 20
    };
}